def normalize_code_key(code: str) -> str:
    """Canonical key without spaces, year, or part numbers."""
    cleaned = re.sub(r":\s*\d{4}.*$", "", str(code))
    cleaned = re.sub(r"\(part\s*\d+\)", "", cleaned, flags=re.IGNORECASE)
    return re.sub(r"\s+", "", cleaned).lower()


def get_certification_type(qco_rules: list[dict[str, Any]], title: str) -> str:
    """Determines the statutory certification category."""
    title_lower = title.lower()
    if any(k in title_lower for k in ["gold", "silver", "jewellery", "artefacts"]):
        return "SCHEME_IV"
    if qco_rules and qco_rules[0].get("is_mandatory"):
        scheme = str(qco_rules[0].get("scheme", "")).upper()
        if "CRS" in scheme or "SCHEME II" in scheme or "REGISTRATION" in scheme:
            return "SCHEME_II"
        return "SCHEME_I"
    return "VOLUNTARY"


